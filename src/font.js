export const FONT_CHARS = Object.keys(G).join('')

/** 15-character bit string (3x5, row by row) for a character, or null. */
export const glyphBits = (ch) => G[String(ch).toUpperCase()] ?? null

/** Render a line of text with the built-in 3x5 font. Unknown characters render as '?'. */
export function text(str, { color = '#ffffff', spacing = 1, lineHeight = 7 } = {}) {
  const c = parseColor(color)
  const lines = String(str).toUpperCase().split('\n')
  const width = Math.max(1, ...lines.map((l) => l.length * (3 + spacing) - spacing))
  const img = new Pixmap(width, lines.length * lineHeight - (lineHeight - 5))
  lines.forEach((line, ly) => {
    ;[...line].forEach((ch, i) => {
      const bits = G[ch] ?? G['?']
      for (let p = 0; p < 15; p++) if (bits[p] === '1') img.set(i * (3 + spacing) + (p % 3), ly * lineHeight + ((p / 3) | 0), c)
    })
  })
  return img
}
